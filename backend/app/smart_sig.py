"""Signatures from smart-contract wallets (ERC-1271), including wallets that are not deployed yet (ERC-6492).

A Circle Wallet is a smart account. It signs the sign-in message in a way only the account contract can check, and
until its first transaction the contract does not exist, so Circle wraps the signature in the ERC-6492 format (the
account factory and its call data travel with the signature). The check is done like viem's `verifyHash`: an
`eth_call` to a throw-away validator contract (the ERC-6492 reference implementation, CC0, as shipped in viem)
that deploys the account when needed and asks it `isValidSignature(hash, signature)`. Nothing is sent to the chain.

Safety notes:
 * the validator runs inside `eth_call`, so a hostile factory in a signature can only waste the caller's own
   request (the endpoint is rate limited and the signature size is capped);
 * the hash being checked is the hash of OUR login message with a one-time nonce, so a signature for anything
   else is worthless;
 * a contract that "validates" every signature only lets its own address sign in, never someone else's.
"""

