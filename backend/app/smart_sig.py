def is_valid_contract_signature(w3: Web3, address: str, digest: bytes, signature: bytes) -> bool:
    """True when `address` (an ERC-1271 account, deployed or counterfactual) accepts `signature` over `digest`."""
    if len(signature) == 0 or len(signature) > MAX_SIGNATURE_BYTES or len(digest) != 32:
        return False
    args = encode(["address", "bytes32", "bytes"], [Web3.to_checksum_address(address), digest, signature])
    try:
        out = w3.eth.call({"data": ERC6492_VALIDATOR_BYTECODE + args.hex()})
    except Exception as exc:  # a reverting validator means "not valid"; an unreachable node is logged
        log.info("smart signature check failed: %s", type(exc).__name__)
        return False
    return len(out) > 0 and int.from_bytes(out, "big") == 1
